uint32_t isqrt32(uint32_t v) {
    /* Raíz entera por bits (método de dígito a dígito): sin divisiones
       ni bucles largos, ~16 iteraciones fijas. */
    uint32_t rem = 0, root = 0;
    for (int i = 0; i < 16; i++) {
        root <<= 1;
        rem = (rem << 2) | (v >> 30);
        v <<= 2;
        if (root < rem) {
            rem -= root | 1;
            root |= 2;
        }
    }
    return root >> 1;
}
